// ── In-Browser Zero-Dependency ZIP Package Builder ───────────────────────────

function crc32(bytes: Uint8Array): number {
  let crc = 0xffffffff;
  for (let i = 0; i < bytes.length; i++) {
    crc ^= bytes[i];
    for (let j = 0; j < 8; j++) {
      crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
    }
  }
  return (crc ^ 0xffffffff) >>> 0;
}

/**
 * Builds the manufacturing ZIP package.
 * Blocks export and throws an Error if the PCB document fails DRC or has missing footprints.
 */
export function buildGerberZip(doc: PCBDocument): Blob {
  const validation = validatePCBDocument(doc);
  if (!validation.isValid) {
    const errorMessages = validation.errors.map((e) => `• [${e.code}] ${e.message}`).join('\n');
    throw new Error(`PCB Export Blocked: DRC Validation Failed with ${validation.errors.length} error(s):\n${errorMessages}`);
  }

  const enc = new TextEncoder();
  const fileDefs = [
    { name: 'circuit.GTL', text: exportGerberTopCopper(doc) },
    { name: 'circuit.GBL', text: exportGerberBottomCopper(doc) },
    { name: 'circuit.GTO', text: exportGerberTopSilkscreen(doc) },
    { name: 'circuit.GTS', text: exportGerberTopSoldermask(doc) },
    { name: 'circuit.GKO', text: exportGerberBoardOutline(doc) },
    { name: 'circuit.DRL', text: exportExcellonDrill(doc) },
    { name: 'circuit.BOM.csv', text: exportBOM(doc) },
    { name: 'README.txt', text: exportFabReadme(doc) },
  ];

  const entries = fileDefs.map((f) => {
    const data = enc.encode(f.text);
    return {
      name: enc.encode(f.name),
      data,
      crc: crc32(data),
      offset: 0,
    };
  });

  const parts: Uint8Array[] = [];
  let offset = 0;

  // Local File Headers + File Data
  for (const e of entries) {
    e.offset = offset;
    const hdr = new Uint8Array(30 + e.name.length);
    const view = new DataView(hdr.buffer);
    view.setUint32(0, 0x04034b50, true);
    view.setUint16(4, 20, true);
    view.setUint16(6, 0, true);
    view.setUint16(8, 0, true);
    view.setUint16(10, 0, true);
    view.setUint32(14, e.crc, true);
    view.setUint32(18, e.data.length, true);
    view.setUint32(22, e.data.length, true);
    view.setUint16(26, e.name.length, true);
    view.setUint16(28, 0, true);
    hdr.set(e.name, 30);

    parts.push(hdr, e.data);
    offset += hdr.length + e.data.length;
  }

  // Central Directory
  const cdStart = offset;
  for (const e of entries) {
    const cd = new Uint8Array(46 + e.name.length);
    const view = new DataView(cd.buffer);
    view.setUint32(0, 0x02014b50, true);
    view.setUint16(4, 20, true);
    view.setUint16(6, 20, true);
    view.setUint16(8, 0, true);
    view.setUint16(10, 0, true);
    view.setUint32(16, e.crc, true);
    view.setUint32(20, e.data.length, true);
    view.setUint32(24, e.data.length, true);
    view.setUint16(28, e.name.length, true);
    view.setUint32(42, e.offset, true);
    cd.set(e.name, 46);

    parts.push(cd);
    offset += cd.length;
  }

  // End of Central Directory
  const eocd = new Uint8Array(22);
  const eocdView = new DataView(eocd.buffer);
  eocdView.setUint32(0, 0x06054b50, true);
  eocdView.setUint16(8, entries.length, true);
  eocdView.setUint16(10, entries.length, true);
  eocdView.setUint32(12, offset - cdStart, true);
  eocdView.setUint32(16, cdStart, true);
  parts.push(eocd);

  return new Blob(parts as unknown as BlobPart[], { type: 'application/zip' });
}
